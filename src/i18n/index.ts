const STRINGS: Record<Locale, Record<StringKey, string>> = { en, ko };

export function t(key: StringKey, params?: Record<string, string | number>): string {
  let out: string = STRINGS[locale][key] ?? en[key];
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      out = out.split(`{${name}}`).join(String(value));
    }
  }
  /*
   * A particle written as {은/는}, {을/를}, {이/가}, {과/와}, {으로/로} is chosen
   * by the word before it — so a name interpolated ahead of it ("'{name}'{은/는}")
   * reads right whatever the name ends in. Quotes and brackets between the
   * word and the particle are skipped when looking for the last syllable.
   */
  return out.replace(/\{([^{}/]+)\/([^{}/]+)\}/g, (_, withFinal: string, withoutFinal: string, offset: number) => {
    const before = out.slice(0, offset).replace(/["'”’)\]»]+$/, '');
    const last = before.charCodeAt(before.length - 1);
    const hasFinal = last >= 0xac00 && last <= 0xd7a3 && (last - 0xac00) % 28 !== 0;
    // A word that is not Hangul (a Latin name, a digit) takes the vowel form.
    return hasFinal ? withFinal : withoutFinal;
  });
}
